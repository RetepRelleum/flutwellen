class Querschnitt(QgsTask):
    """
    Querschnitt is a QGIS task class for calculating and analyzing
    cross-sections (Querschnitt) in a hydrological context, specifically
    for flood wave computations.
    Args:
        dlg: The dialog object containing user interface elements and input values.
    Attributes:
        dlg: Reference to the dialog UI.
        raster: Raster object initialized from the selected file path.
        proName: Project name from the dialog input.
        fluss: FlussL object for river geometry.
        mupe: Mupe object for vector and elevation calculations.
        damm: DammL object for storing cross-section data.
        intL: IntL object for storing intensity data.
        vo: Value from dialog spin box (velocity or similar).
        qb_: Value from dialog spin box (discharge or similar).
        k: Value from dialog spin box (coefficient or similar).
    Methods:
        finished(result):
            Called when the task is finished. Prints a message if the result is False.
        run():
            Main computation loop. Iterates over river vertices, calculates
            cross-sections, determines geometry type (rectangle, triangle,
            trapezoid, parabola), computes hydraulic parameters, and stores
            results in the dam and intensity layers.
        r_ymax(ls, i, k, qmm, l):
            Calculates maximum height and area for a rectangular cross-section.
        interpolation(i, dmax, dm, um):
            Performs linear interpolation between tabulated values.
        d_ymax(ls, i, k, qmm, m):
            Calculates maximum height and area for a triangular cross-section.
        t_ymax(ls, i, k, qmm, m, l):
            Calculates maximum height and area for a trapezoidal cross-section.
        p_ymax(ls, i, k, qmm, p):
            Calculates maximum height and area for a parabolic cross-section.
        setMarker(pk, col):
            Sets a marker on the QGIS map canvas at the given point with a specified color.
        qmax_div_qb(x, vo, j, k):
            Computes the ratio of maximum discharge to base discharge using tabulated factors.
    Notes:
        - This class is designed for use within a QGIS plugin environment.
        - It relies on several custom classes (Raster, FlussL, Mupe, DammL, IntL)
          and QGIS API objects.
        - The main logic involves iteratively constructing cross-sections,
          classifying their geometry, and storing hydraulic properties for further
          analysis or visualization.
    """

    def __init__(self, dlg):
        description = 'Flutwellenberechnung 2'
        super().__init__(description, QgsTask.CanCancel)
        self.dlg = dlg
        self.raster = Raster(self.dlg.mQgsFileWidget.filePath())
        self.raster.setVisibility(False)
        self.proName = dlg.lineEditProjetName.text()
        self.fluss = FlussL(self.proName)
        self.mupe = Mupe(self.raster)
        self.damm = DammL(self.proName)
        self.intL = IntL(self.proName)
        self.vo = self.dlg.sBv.value()
        self.qb_ = self.dlg.sBQb.value()
        self.k = self.dlg.spBR.value()

    def finished(self, result):
        if result:
            pass
        else:
            print("Finished Function False ")

    def run(self):
        try:
            self.damm.damm.startEditing()
            request = QgsFeatureRequest().setFilterExpression(
                "type = 'Querschnitt' or type = 'Ueberlauf'")
            for f in self.damm.damm.getFeatures(request):
                self.damm.damm.deleteFeature(f.id())
            self.damm.damm.commitChanges()
            p = QgsProject.instance()
            if self.intL.intensitaet:
                p.removeMapLayer(self.intL.intensitaet)
            self.intL = IntL(self.proName)
            ls = self.fluss.getFluss()
            t = 0
            self.dlg.progressBar.setRange(0, ls.vertexCount() - 2)
            for i in range(ls.vertexCount() - 2):
                self.dlg.progressBar.setValue(i + 1)
                lsl = QgsLineString()
                lsr = QgsLineString()
                lsx = QgsLineString()
                lsp = QgsLineString()
                point0l = ls.pointN(i + 1)
                point0l.setX(point0l.x() - 0.001)
                point0r = point0l.clone()
                point0r.setX(point0r.x() + 0.001)
                hmin = point0l.z()
                lsl.addVertex(point0l)
                lsx.addVertex(
                    QgsPoint(point0l.x(), point0l.y(), point0l.z(), 0))
                dirV = self.mupe.qgsVecDirNorm(point0l, ls.pointN(i))
                deltaHoehe = 0.01
                niveauHoehe = hmin + deltaHoehe
                qm2 = 0
                weiter = True
                h1 = ls.startPoint().z()
                h2 = point0l.z()
                qm_qb, xvo, ki = self.qmax_div_qb(
                    10 * i + 10, self.vo, (h1 - h2) / (10 * i + 10), self.k)
                qmm = self.qb_ * qm_qb
                typq = ''
                pil = 1
                pir = -1

                while weiter:
                    ueberlauf = False
                    if point0l.z() <= niveauHoehe and point0l.z() != 0.0:
                        point0l = self.insertPoint(
                            lsl, lsx, point0l, hmin, dirV, pil)
                        pil += 1
                        niveauHoehe -= deltaHoehe
                        if (niveauHoehe - hmin) == 0:
                            niveauHoehe += deltaHoehe
                    if point0r.z() <= niveauHoehe and point0r.z() != 0.0:
                        point0r = self.insertPoint(
                            lsr, lsx, point0r, hmin, dirV, pir)
                        pir -= 1
                        niveauHoehe -= deltaHoehe
                        if (niveauHoehe - hmin) == 0:
                            niveauHoehe += deltaHoehe

                    niveauHoehe += deltaHoehe
                    qm2 = 0
                    lt = 0
                    for h_ in lsr:
                        qm2 += abs(niveauHoehe - h_.z())
                        if h_.z() < (hmin + (niveauHoehe - hmin) * 0.85):
                            lt += 1
                    for h_ in lsl:
                        qm2 += abs(niveauHoehe - h_.z())
                        if h_.z() < (hmin + (niveauHoehe - hmin) * 0.85):
                            lt += 1
                    laenge_ = lsl.endPoint().distance(lsr.endPoint())
                    if lt > laenge_:
                        lt = 1
                    if qmm <= 0:
                        break
                    ymaxR, fmaxR, umR = self.r_ymax(
                        ls, i, self.k, qmm, laenge_)
                    ymaxD, fmaxD, umD = self.d_ymax(
                        ls, i, self.k, qmm, (laenge_ / 2) / (niveauHoehe - hmin))
                    ymaxT, fmaxT, umT = self.t_ymax(
                        ls, i, self.k, qmm, ((laenge_ - lt) / 2) / (niveauHoehe - hmin), lt)
                    ymaxP, fmaxP, umP = self.p_ymax(
                        ls, i, self.k, qmm, laenge_)
                    dq = qm2 / 100 * 15
                    dy = (niveauHoehe - hmin) / 100 * 15
                    dP = 0.15
                    if (fmaxR - dq * dP) <= qm2 <= (fmaxR + dq) and \
                            (ymaxR - dy * dP) <= (niveauHoehe - hmin) <= (ymaxR + dy):
                        typq = 'Rechteck'
                        break
                    if (fmaxD - dq * dP) <= qm2 <= (fmaxD + dq) and \
                            (ymaxD - dy * dP) <= (niveauHoehe - hmin) <= (ymaxD + dy):
                        typq = 'Dreieck'
                        break
                    if (fmaxT - dq * dP) <= qm2 <= (fmaxT + dq) and \
                            (ymaxT - dy * dP) <= (niveauHoehe - hmin) <= (ymaxT + dy):
                        typq = 'Trapez'
                        break
                    if (fmaxP - dq * dP) <= qm2 <= (fmaxP + dq) and \
                            (ymaxP - dy * dP) <= (niveauHoehe - hmin) <= (ymaxP + dy):
                        typq = 'Parabel'
                        break
                    if qm2 > 1.5 * fmaxR or qm2 > 3 * fmaxP:
                        typq = 'Unbekannt'
                        break
                for p in lsr:
                    lsp.addVertex(p)
                for p in lsl.reversed():
                    lsp.addVertex(p)
                querStr = 'Querschnitt'
                lsrZ = lsr.endPoint().z()
                lslZ = lsl.endPoint().z()

                if lsrZ < (niveauHoehe - 3 * deltaHoehe) or lslZ < (niveauHoehe - 3 * deltaHoehe):
                    ueberlauf = True
                    querStr = 'Ueberlauf'
                polygonL = QgsPolygon(lsp)
                v = qmm / fmaxR
                t += 10 / v
                el = niveauHoehe + (v ** 2) / (2 * 9.81)
                if i > 0 and v > 0:
                    if typq == 'Rechteck':
                        self.damm.insertData(polygonL, querStr, 0, fmaxR, 0, laenge_, i * 10, 0, ymaxR, typq, qmm, 0,
                                             xvo, ki, umR, ueberlauf, v, niveauHoehe, el, t)
                    elif typq == 'Dreieck':
                        self.damm.insertData(polygonL, querStr, 0, fmaxD, 0, laenge_, i * 10, 0, ymaxD,
                                             typq, qmm, 0, xvo, ki, umD, ueberlauf, v, niveauHoehe, el, t)
                    elif typq == 'Trapez':
                        self.damm.insertData(polygonL, querStr, 0, fmaxT, 0, laenge_, i * 10, 0, ymaxT,
                                             typq, qmm, 0, xvo, ki, umT, ueberlauf, v, niveauHoehe, el, t)
                    elif typq == 'Parabel':
                        self.damm.insertData(polygonL, querStr, 0, fmaxP, 0, laenge_, i * 10, 0, ymaxP,
                                             typq, qmm, 0, xvo, ki, umP, ueberlauf, v, niveauHoehe, el, t)
                    else:
                        self.damm.insertData(polygonL, querStr, 0, fmaxR, 0, laenge_, i * 10, 0, ymaxR,
                                             typq, qmm, 0, xvo, ki, umR, ueberlauf, v, niveauHoehe, el, t)
                    min_p = 0
                    max_p = 0
                    for p in lsx:
                        if min_p > p.m():
                            min_p = p.m()
                        if max_p < p.m():
                            max_p = p.m()
                    for p in lsx:
                        if p.m() == min_p or p.m() == max_p and not ueberlauf:
                            p.setZ(niveauHoehe)
                        intens = abs((niveauHoehe - p.z()) * v)
                        if ueberlauf:
                            intens = intens * -1
                        h = niveauHoehe - p.z()
                        self.intL.insertData(
                            p, intens, v, h, i * 10, p.m(), niveauHoehe, el)
            self.raster.setVisibility(False)
        except Exception as X:
            print(X)

    def insertPoint(self, lsl_, lsx_, point0l_, hmin, dirV, pi):
        if pi < 0:
            point0l_ = self.mupe.qgsVecAddM(point0l_, dirV)
        else:
            point0l_ = self.mupe.qgsVecAdd(point0l_, dirV)
        px = point0l_.clone()
        px.setX(px.x() + dirV.y() * (px.z() - hmin))
        px.setY(px.y() - dirV.x() * (px.z() - hmin))
        lsl_.addVertex(px)
        lsx_.addVertex(QgsPoint(point0l_.x(), point0l_.y(), point0l_.z(), pi))
        return point0l_

