    def interpolation(self, i, dmax, dm, um):
        umx1 = um[i]
        dm1 = dm[i]
        umx2 = um[i - 1]
        dm2 = dm[i - 1]
        umx = umx2 + (umx1 - umx2) / (dm1 - dm2) * (dm1 - dmax)
        return umx

